const allLanguageCodes: Language[] = ["tr", "en", "de", "fr", "es", "ar", "ru", "pt", "ja", "zh", "ko", "tl", "hi"];

function detectLanguage(): Language {
  const browserLang = navigator.language || (navigator as any).userLanguage || "tr";
  const lang = browserLang.split("-")[0].toLowerCase() as Language;
  return allLanguageCodes.includes(lang) ? lang : "en";
}

interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: "tr",
  setLanguage: () => {},
  t: (key) => key,
});

export const useLanguage = () => useContext(LanguageContext);

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [language, setLanguage] = useState<Language>(() => {
    const saved = localStorage.getItem("vector-lang");
    if (saved && allLanguageCodes.includes(saved as Language)) return saved as Language;
    return detectLanguage();
  });

  useEffect(() => {
    localStorage.setItem("vector-lang", language);
    document.documentElement.lang = language;
    document.documentElement.dir = language === "ar" ? "rtl" : "ltr";
  }, [language]);

  const t = (key: string): string => {
    return translations[language]?.[key] || translations.en[key] || translations.tr[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};
